/** Release body -> clean lines (markdown noise, links, commit hashes, dates-as-lines, headings dropped). Years are kept here; masked later. */
export function clean(body) {
  const t = (body || '').replace(/\r/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/```[\s\S]*?```/g, '').replace(/<[^>]+>/g, '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/https?:\/\/\S+/g, '').replace(/\s*\(?#\d+\)?/g, '').replace(/\s+by @[\w-]+( in)?/g, '').replace(/@[\w-]+/g, '')
    .replace(/\*\*Full Changelog\*\*.*/gi, '').replace(/\b[0-9a-f]{7,40}\b/g, '')
    .replace(/,?\s*see\s*(and\s*)?\(\s*(and\s*)?\)/gi, '').replace(/\(\s*(and\s*)?\)/g, '').replace(/\[\s*\]/g, '').replace(/\(\s*(?:(?:in|and)\s*)+\)?/g, '').replace(/\(\s*(?:[-–,]\s*)*\)/g, '').replace(/,?\s*see\s+(and\s+)?for more details\.?/gi, '').replace(/\\"/g, '"').replace(/\\([\[\]_*#()<>`])/g, '$1');
  const out = [];
  for (let l of t.split('\n')) {
    l = l.trim().replace(/^>+\s*/, '').replace(/^#+\s*/, '').replace(/^[-*•]+\s+/, '').replace(/\*\*/g, '').replace(/`/g, '').replace(/\s#{2,6}\s+/g, ' ').replace(/\s+/g, ' ').replace(/\s+[-,:]$/, '').trim();
    const words = l.split(/\s+/).length;
    if (!l || l.length <= 12 || words < 3 || l.replace(/[^A-Za-z]/g, '').length < 10) continue;
    if (/^[-=_*\s]+$/.test(l) || /:$/.test(l) && words <= 5 || BOILER.test(l)) continue;
    if (/^[\[{}(\/]/.test(l) && !/^\[[\w\/\-, .]+\]\s/.test(l)) continue;
    if (/[{};]$|^\/\//.test(l) || /\|/.test(l)) continue;
    if ((l.match(/\(/g) || []).length !== (l.match(/\)/g) || []).length || (l.match(/\[/g) || []).length !== (l.match(/\]/g) || []).length) continue;
    if ((l.match(/[,:]/g) || []).length > 18 || /[,:]\s*[,:]/.test(l)) continue;
    if (/^\W*$/.test(l.replace(/▇/g, ''))) continue;
    if (!out.includes(l)) out.push(l);
  }
  return out;
}

const lineCut = (l) => (l.length > 160 ? l.slice(0, 157) + '…' : l);
const pool = [];
const repos = [];
const stats = { drop_leak: 0, drop_short: 0 };
for (const f of readdirSync('raw').filter((f) => !f.startsWith('_') && f.endsWith('.json'))) {
  const id = f.replace('.json', '').replace('__', '/');
  let rel; try { rel = JSON.parse(readFileSync('raw/' + f, 'utf8')); } catch { continue; }
  const meta = JSON.parse(readFileSync('raw/_meta_' + f, 'utf8'));
  const repo = { id, name: disp(id), lang: LANG[meta.language] || meta.language || null, stars: meta.stargazers_count, since: +meta.created_at.slice(0, 4), alias: EXTRA[id] || [] };
  if (!repo.alias.length) delete repo.alias;
  const cands = [];
  for (const r of rel) {
    if (r.draft || r.prerelease || !r.published_at) continue;
    const year = +r.published_at.slice(0, 4);
    if (year < repo.since) continue;
    const raw = clean(r.body).map(lineCut).slice(0, 7);
    const lines = raw.map((l) => l.replace(YEAR, MASK));
    const shown = lines.map((l) => redact(l, repo));
    const visible = shown.join('').replace(/[▇\s]/g, '').length;
    const bars = shown.join('').split('▇').length - 1;
    if (lines.length < 3 || visible < 120 || visible > 760 || bars > 40) { stats.drop_short++; continue; }
    // leak scan on exactly what the player can see before guessing
    if (leaks(shown.join('\n'), repo) || leaks(redactTag(r.tag_name, repo), repo)) { stats.drop_leak++; continue; }
    const c = { repo: id, tag: r.tag_name, year, date: r.published_at.slice(0, 10), lines, url: r.html_url };
    if (raw.some((l, i) => l !== lines[i])) c.raw = raw;
    cands.push(c);
  }
  if (!cands.length) continue;
  repos.push(repo);
  // up to 4 per repo, spread over distinct years
  const byYear = new Map(); for (const c of cands) if (!byYear.has(c.year)) byYear.set(c.year, c);
  const ys = [...byYear.values()].sort((a, b) => a.year - b.year);
  const n = Math.min(4, ys.length);
  const idx = new Set(); for (let i = 0; i < n; i++) idx.add(Math.round((i * (ys.length - 1)) / Math.max(1, n - 1)));
  for (const i of idx) pool.push(ys[i]);
}
repos.sort((a, b) => a.id.localeCompare(b.id));
const seen = new Set(); const puzzles = pool.filter((p) => !seen.has(p.repo + p.tag) && seen.add(p.repo + p.tag));
writeFileSync('../data.json', JSON.stringify({ repos, puzzles, built: new Date().toISOString().slice(0, 10) }));
console.log(repos.length, 'repos', puzzles.length, 'puzzles', JSON.stringify(stats));
